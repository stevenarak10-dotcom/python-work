tahed = ["A", "B", "C", "D", "E", "F"]
print(tahed[1:4])
print(tahed[:3])
print(tahed[3:])
print(tahed[-3:-1])
print(tahed[::-1])
# mugav viis järjendi tagurpidi printimiseks on kasutada järjendi viilutamist koos sammuga -1. See tagastab uue järjendi, mis sisaldab kõiki algse järjendi elemente vastupidises järjekorras.